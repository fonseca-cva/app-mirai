// REBALANCE BATERÍA 5 CONSTRUCTOS (TANDA A, plan Camilo): perfilCognitivo pasa de
// 4 a 5 claves con 'numerico'. Regla PENDIENTE REVALIDACIÓN: el peso de 'patrones'
// se reparte numerico/patrones según el área de la carrera (60/40 en ingeniería,
// ciencias, tecnología, datos y contabilidad; 30/70 en salud, educación, sociales,
// arte y comunicación; 50/50 en técnicas industriales). Suma 1.0 por fila intacta.
//
// Orden vigente: nada en producción hasta (a) diff reconciliado, (b) ingesta SIES,
// (c) cifras banco verificadas, (d) notas honestas aprobadas.
//
// Fuentes por campo (una fuente por tipo, sin excepción):
//   empleabilidad, ingreso, duración, arancel → mifuturo.cl (SIES)
//   matrícula, oferta                    → CNED/INDICES
//   retención 1er año                    → SIES informes
//   tendencia                            → OIT / WEF / Observatorio Laboral SENCE
//   demanda ocupacional                  → Observatorio Laboral SENCE

import type { DimensionCodigo } from "@/lib/data/contextos";

// ---------------------------------------------------------------------------
// Tipos
// ---------------------------------------------------------------------------

/** Tendencia proyectada a 5-10 años para una carrera */
export type TendenciaCarrera = "expansion" | "estable" | "transformacion" | "contraccion";

/** Referencia bibliográfica o documental de un dato */
export interface FuenteRef {
  fuente: string | null;      // nombre de la fuente, ej. "mifuturo.cl"
  anio: number | null;        // año del dato
  url?: string | null;        // opcional, para verificación
}

/** Empleabilidad al 1er año: % de titulados que trabajan al año de egreso */
export interface Empleabilidad1erAnio {
  porcentaje: number | null;  // 0-100
  fuente: string | null;
  anio: number | null;
}

/** Rango de ingreso bruto al 4to año (CLP) entre instituciones */
export interface Ingreso4toAnioRango {
  min: number | null;
  max: number | null;
  fuente: string | null;
  anio: number | null;
}

/** Duración real promedio de la carrera en semestres */
export interface DuracionReal {
  semestres: number | null;
  fuente: string | null;
}

/** Rango de arancel de referencia anual (CLP) */
export interface ArancelRango {
  min: number | null;
  max: number | null;
  fuente: string | null;
  anio: number | null;
}

/** Área principal + hasta 2 secundarias con peso (0-1) */
export interface AreaMapping {
  principal: DimensionCodigo;
  secundarias?: Array<{ codigo: DimensionCodigo; peso: number }>;
}

/** Vía formativa: declara contra qué tipo de institución SIES matchea esta carrera.
 *  "universitaria" → fila tipo_institucion="Universidad".
 *  "tecnica_ip_cft" → fila IP o CFT (técnicos puros: CFT; gestión: IP).
 *  Antes se derivaba del prefijo del id (`tecnico_*`); ahora es explícita para no
 *  depender de una convención de nombrado frágil (ej. `gastronomia` es técnica). */
export type ViaFormativa = "universitaria" | "tecnica_ip_cft";

/** Carrera genérica (no por institución) */
export interface Carrera {
  id: string;                          // slug único, ej. "psicologia"
  nombre: string;                      // nombre oficial genérico
  nombresAlternativos: string[];       // ej. ["Licenciatura en Psicología"]
  via: ViaFormativa;                   // vía para desambiguar el match SIES por tipo de institución
  area: AreaMapping;                   // mapeo a dimensiones
  perfilCognitivo: {
    patrones: number | null;           // PENDIENTE REVALIDACIÓN (reparto por área, Tanda A)
    numerico: number | null;           // PENDIENTE REVALIDACIÓN (nuevo constructo, Tanda A)
    espacial: number | null;
    memoria: number | null;
    comunicacion: number | null;
  };
  // -- Datos de mercado (todos con fuente y año) --
  empleabilidad1erAnio: Empleabilidad1erAnio;
  ingreso4toAnioRango: Ingreso4toAnioRango;
  duracionRealPromedio: DuracionReal;
  arancelReferenciaRango: ArancelRango;
  tendencia: TendenciaCarrera | null;
  tendenciaFuente: FuenteRef;          // ej. { fuente: "OIT Future of Work 2025", anio: 2025 }
  tendenciaNota: string | null;        // frase corta explicativa
  /** Pruebas PAES relevantes para postular a esta carrera */
  familiaPaes: string[];              // ej. ["CL", "M1", "Ciencias"]
  /** Frase honesta — la redacta Camilo. Se muestra en el informe */
  notaHonesta: string | null;
  /** Fecha de la última curación de datos */
  actualizadoEn: string | null;       // ISO date string
}

