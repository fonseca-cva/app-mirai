/** Busca una carrera por su id. Retorna undefined si no existe. */
export function carreraPorId(id: string): Carrera | undefined {
  return carreras.find((c) => c.id === id);
}

/** Filtra carreras por dimensión principal o secundaria. */
export function carrerasPorDimension(dimension: DimensionCodigo): Carrera[] {
  return carreras.filter(
    (c) =>
      c.area.principal === dimension ||
      c.area.secundarias?.some((s) => s.codigo === dimension),
  );
}